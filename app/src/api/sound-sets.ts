/**
 * Which recordings each game plays.
 *
 * ## Why this is per game and not one set for the app
 *
 * All twenty-three slots shared one synthesised sound palette, and that was the
 * single largest reason they still felt like one machine after the art, the
 * grids, the cabinets and the bonuses had all been made different. A player does
 * not experience a slot as a paytable — they experience a rhythm, and the sound
 * IS the rhythm. Two games that look different and sound identical are one game.
 *
 * So the assignment is per GAME, like the symbols and the cabinets, and it is
 * written out rather than derived from a hash of the id: a table can be read,
 * argued with and corrected, and "why does Frost Peak sound like that" has an
 * answer somebody chose.
 *
 * ## What is actually in the library
 *
 * Eighty-six files, generated by the founder in two batches: reel spins and
 * stops, lever pulls, wins, jackpot fanfares, an anticipation riser, scatter,
 * coin-lock, cascade, near-miss, taps, ticks, four roulette sounds, and
 * twenty-four thirty-second music beds — four for each of six theme families.
 *
 * Three uploads are discarded rather than used: `reel-stop-5` and `cascade-2`
 * are byte-identical duplicates of their siblings, and `near-miss-4` decodes at
 * a peak of 0.046, which is silence with a filename.
 *
 * That is enough to give each game a distinct COMBINATION but not a distinct
 * file for every slot — with four spin recordings across twenty-three games,
 * some sharing is arithmetic rather than laziness. The sets below are arranged
 * so that games sharing a spin do not also share a win, and so that neighbours
 * in the lobby never sound the same.
 *
 * ## The mechanical layer is shared on purpose
 *
 * Reel stops, taps and the counter tick are the same across all twenty-three.
 * A reel stop is the sound of the machine's MECHANISM, and the mechanism does
 * not change between themes — five different click recordings across the
 * catalogue would read as five different qualities of build, not as five
 * different games. What makes a game its own is its music, its spin and its
 * fanfare, and those are all varied below.
 *
 * Everything still falls back to the synthesised version when a file has not
 * loaded, so a slow network makes the game sound thinner rather than silent.
 */

