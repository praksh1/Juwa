/**
 * The music, by theme family.
 *
 * Four thirty-second beds per family, so two games sharing a family still do
 * not share a bed — which is the whole reason there are four. Thirty seconds
 * rather than sixty because that is what the free tier renders; they loop, and
 * a bed nobody is listening to closely loops fine at thirty.
 *
 * Which family a game belongs to is written out below rather than derived from
 * its art or its maths, because it is a musical judgement: Ocean Drift and
 * Emerald Nights share nothing except that both want something wide and slow
 * underneath them.
 */
