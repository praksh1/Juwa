export function soundSetFor(gameId: string): SoundSet {
  // A game with no entry gets the classic set rather than silence — a new theme
  // should be playable the moment it is added to the catalogue.
  return SOUND_SETS[gameId] ?? SOUND_SETS['juwa-classic-slots']!;
}
